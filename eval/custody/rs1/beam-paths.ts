/**
 * The BEAM paths an RS1 mint may put on a machine (F28, GBEV-3): BEAM's pipeline code (src/), requirements.txt,
 * LICENSE and README.md, the topics files of the tiers that have dev conversations, and every dev conversation's full
 * chat (chat.json), its canonical chat when BEAM ships a truncated one (the manifest's chat_trunecated.json) and its
 * questions file. mint.sh checks out exactly these (eval/custody/rs1/beam-paths.txt, git
 * sparse-checkout patterns) through eval/custody/rs1/beam-checkout.sh, and validate.ts builds its public index over
 * the same chats.
 *
 * Excluded, derived from the committed split and dataset files so the list can't drift from them:
 *   - every conversation a BEAM split file marks sealed (eval/decisions/splits/beam-*.json): BEAM-100K's 14 (Q1 S2a),
 *     BEAM-500K's 24 (reserved for P4 E1), BEAM-1M's 24 (Q1 S2b) and all ten BEAM-10M conversations (Q1 S1);
 *   - the whole 10M tier, topics included: no BEAM-10M conversation is dev, so neither its chats nor topics/10M appear;
 *   - every other file in a dev conversation's folder (BEAM's pickles, plans and profile) and BEAM's per-tier
 *     chats/<tier>/topics.json copies, which no public mint reads.
 * A conversation in the dataset manifest (eval/decisions/datasets/beam-b2da22e.json) that its split file names neither
 * dev nor sealed refuses the list, so a new conversation never counts as public by default.
 *
 *   bun eval/custody/rs1/beam-paths.ts --write    rewrite beam-paths.txt from the split and dataset files
 *   bun eval/custody/rs1/beam-paths.ts --check    exit 1 when beam-paths.txt differs from them
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { loadSplit } from '../../runner/decisions/splits.ts';

export const BEAM_PATHS_FILE = join(import.meta.dir, 'beam-paths.txt');
const MANIFEST = resolve(import.meta.dir, '../../decisions/datasets/beam-b2da22e.json');
/** BEAM's own files every mint needs: src/ holds the pipeline rs1_mint.py imports. */
const CODE = ['src/', 'requirements.txt', 'LICENSE', 'README.md'];
/** Each BEAM tier: its split file, its size in the dataset manifest, and its topics file in BEAM's tree. */
const TIERS = [
  { split: 'beam-100k', size: '100k', topics: 'topics/100k/100k_topics.json' },
  { split: 'beam-500k', size: '500k', topics: 'topics/500k/500k_topics.json' },
  { split: 'beam-1m', size: '1m', topics: 'topics/1M/1M_topics.json' },
  { split: 'beam-10m', size: '10m', topics: 'topics/10M/10M_topics.json' },
];

interface ManifestEntry { conversation: string; chat_path: string; questions_path: string }

/** The allowed paths, relative to BEAM's root; a directory ends in "/". */
export function deriveBeamPaths(): string[] {
  const sizes = JSON.parse(readFileSync(MANIFEST, 'utf8')).sizes as Record<string, ManifestEntry[]>;
  const topics: string[] = [], chats: string[] = [];
  for (const tier of TIERS) {
    const split = loadSplit(tier.split), entries = sizes[tier.size] ?? [];
    const unsplit = entries.filter(e => !split.dev.includes(e.conversation) && !split.sealed.includes(e.conversation));
    if (unsplit.length) throw new Error(`${tier.split}: ${unsplit.map(e => e.conversation).join(', ')} in no split`);
    const unknown = split.dev.filter(id => !entries.some(e => e.conversation === id));
    if (unknown.length) throw new Error(`${tier.split}: dev conversations ${unknown.join(', ')} are not in ${MANIFEST}`);
    const dev = entries.filter(e => split.dev.includes(e.conversation));
    if (!dev.length) continue;
    topics.push(tier.topics);
    for (const e of dev) chats.push(`${dirname(e.chat_path)}/chat.json`, ...(e.chat_path.endsWith('/chat.json') ? [] : [e.chat_path]), e.questions_path);
  }
  return [...CODE, ...topics, ...chats];
}

export function renderBeamPaths(): string {
  return [
    '# BEAM paths the RS1 mint checks out (F28), as git sparse-checkout patterns: pipeline code, licence, readme, the',
    "# topics of tiers with dev conversations, and each dev conversation's chat files and questions file. No sealed",
    '# conversation and nothing of the 10M tier. Generated by `bun eval/custody/rs1/beam-paths.ts --write` from',
    '# eval/decisions/splits/beam-*.json and eval/decisions/datasets/beam-b2da22e.json; do not edit by hand.',
    ...deriveBeamPaths().map(p => `/${p}`),
  ].join('\n') + '\n';
}

/** The committed list as paths relative to BEAM's root, and the SHA-256 of the file. */
export function readBeamPaths(file = BEAM_PATHS_FILE): { paths: string[]; sha256: string } {
  const text = readFileSync(file);
  const paths = text.toString('utf8').split('\n').filter(l => l && !l.startsWith('#')).map(l => l.replace(/^\//, ''));
  return { paths, sha256: createHash('sha256').update(text).digest('hex') };
}

if (import.meta.main) {
  const mode = process.argv[2];
  if (mode === '--write') writeFileSync(BEAM_PATHS_FILE, renderBeamPaths());
  else if (mode === '--check') {
    if (readFileSync(BEAM_PATHS_FILE, 'utf8') !== renderBeamPaths()) { console.error('beam-paths.txt differs from the split and dataset files; run with --write'); process.exit(1); }
  } else { console.error('usage: bun eval/custody/rs1/beam-paths.ts --write | --check'); process.exit(2); }
}
