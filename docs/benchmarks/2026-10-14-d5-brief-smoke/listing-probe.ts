import { spawn } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
const [build, home, surface, advertised] = process.argv.slice(2);
const cfgPath = join(home, '.gbrain', 'config.json');
const cfg = JSON.parse(readFileSync(cfgPath, 'utf8'));
cfg.mcp = { ...(cfg.mcp ?? {}) }; if (advertised === 'none') delete cfg.mcp.advertised_surface; else cfg.mcp.advertised_surface = advertised;
writeFileSync(cfgPath, JSON.stringify(cfg, null, 2));
const p = spawn('bun', [join(build, 'src/cli.ts'), 'serve', '--surface', surface], { env: { ...process.env, GBRAIN_HOME: home, HOME: join(home, '..', 'uh') }, cwd: home });
let buf = ''; const waiters = new Map<number, (m: any) => void>();
p.stdout.on('data', d => { buf += d; let i; while ((i = buf.indexOf('\n')) >= 0) { const line = buf.slice(0, i); buf = buf.slice(i + 1); try { const m = JSON.parse(line); if (m.id !== undefined && waiters.has(m.id)) waiters.get(m.id)!(m); } catch {} } });
p.stderr.on('data', () => {});
const req = (id: number, method: string, params: any) => new Promise<any>(r => { waiters.set(id, r); p.stdin.write(JSON.stringify({ jsonrpc: '2.0', id, method, params }) + '\n'); });
await req(1, 'initialize', { protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'probe', version: '0' } });
p.stdin.write(JSON.stringify({ jsonrpc: '2.0', method: 'notifications/initialized' }) + '\n');
const list = await req(2, 'tools/list', {});
const tools = list.result.tools;
const cp = tools.find((t: any) => t.name === 'context_pack');
console.log(JSON.stringify({ surface, advertised, listed: tools.length, context_pack: !!cp, props: cp ? Object.keys(cp.inputSchema.properties) : null }));
p.kill();
process.exit(0);
